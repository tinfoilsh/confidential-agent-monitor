func source(name, text string) map[string][]byte { return map[string][]byte{name: []byte(text)} }

func hasViolation(violations []string, want string) bool {
	return slices.ContainsFunc(violations, func(v string) bool { return strings.Contains(v, want) })
}

func TestSourceBoundaries(t *testing.T) {
	for _, tc := range []struct{ name, file, code, want string }{
		{"new library", "core/newhelper/newhelper.go", "package newhelper", "outside the approved"},
		{"new command", "cmd/new/main.go", "package main", "outside the approved"},
		{"main in library", "core/core.go", "package main", "expected package core"},
		{"unneeded core dependency", "connector/tcp/tcp.go", `package tcp; import "` + module + `/core/approval"`, "unapproved dependency core/approval"},
		{"peer protocol", "connector/web/web.go", `package web; import "` + module + `/connector/email"`, "another protocol"},
		{"product format", "connector/worker/worker.go", `package worker; import "` + module + `/cmd/perimeter/format"`, "product or composition"},
		{"UI", "core/core.go", `package core; import "` + module + `/ui"`, "product or composition"},
		{"product SDK", "core/attestation/attestation.go", `package attestation; import "github.com/tinfoilsh/tinfoil-go/verify"`, "product SDK"},
		{"policy SDK", "core/core.go", `package core; import _ "github.com/open-policy-agent/opa/v1/rego"`, "product SDK"},
		{"raw import", "connector/tcp/tcp.go", "package tcp; import `" + module + "/core/approval`", "unapproved dependency"},
		{"escaped import", "connector/tcp/tcp.go", `package tcp; import "\u0067ithub.com/tinfoilsh/confidential-agent-monitor/core/approval"`, "unapproved dependency"},
		{"inactive build", "connector/tcp/extra_windows.go", "//go:build windows\n\npackage tcp\nimport \"" + module + "/core/approval\"", "unapproved dependency"},
		{"generated import", "connector/tcp/generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage tcp\nimport \"" + module + "/core/approval\"", "unapproved dependency"},
		{"flag configuration", "core/core.go", `package core; import f "flag"`, "process configuration"},
		{"signal configuration", "core/core.go", `package core; import "os/signal"`, "process configuration"},
		{"implicit startup", "connector/worker/worker.go", "package worker; func init() {}", "implicit initialization"},
		{"environment alias", "connector/worker/worker.go", `package worker; import process "os"; var setting = process.Getenv("SETTING")`, "os.Getenv"},
		{"environment function value", "core/core.go", `package core; import "os"; var read = os.LookupEnv`, "os.LookupEnv"},
		{"environment snapshot", "connector/worker/worker.go", `package worker; import process "os"; var environment = process.Environ()`, "os.Environ"},
		{"process exit", "core/core.go", `package core; import process "os"; func stop() { process.Exit(1) }`, "os.Exit"},
		{"fatal log", "core/core.go", `package core; import logger "log"; func stop() { logger.Fatalf("failed") }`, "log.Fatalf"},
		{"dot import", "core/core.go", `package core; import . "os"; var setting = Getenv("SETTING")`, "dot imports"},
		{"access vocabulary", "core/facts/facts.go", "package facts; type Vocabulary struct{}", "access model"},
		{"access resolution", "core/facts/facts.go", "package facts; type Input struct{}; func (Input) Resolve() {}", "resolve application access"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := inspect(source(tc.file, tc.code), packages)
			if !hasViolation(got.Violations, tc.want) {
				t.Fatalf("wanted %q, got %v", tc.want, got.Violations)
			}
		})
	}
}

func TestSourceAllowsExplicitMechanicsAndComposition(t *testing.T) {
	files := source("connector/worker/worker.go", `package worker
import (
    // import "`+module+`/cmd/perimeter/format" is an example, not a dependency.
    network "`+module+`/core/transport/netx"
    "`+module+`/core/facts"
)
var example = `+"`import \""+module+"/cmd/perimeter/format\"`"+`
`)
	files["cmd/perimeter/settings.go"] = []byte(`package main; import "flag"; import "os"; var setting = os.Getenv("SETTING"); func init() { flag.Parse() }`)
	files["core/core_test.go"] = []byte(`package core_test; import "` + module + `/cmd/perimeter/format"; func TestFixture() {}`)
	files["core/shadow.go"] = []byte(`package core; import "os"; func f() { os := struct { Getenv func(string) string }{}; os.Getenv("not the os package") }`)
	files["core/helper.go"] = []byte(`package core; type helper struct{}; func (helper) init() {}`)
	got := inspect(files, packages)
	if len(got.Violations) != 0 {
		t.Fatal(got.Violations)
	}
	if !slices.Equal(got.Packages["connector/worker"].Imports, []string{module + "/core/facts", module + "/core/transport/netx"}) {
		t.Fatal(got.Packages["connector/worker"].Imports)
	}
}

func TestHardFencesSurviveAllowlistEdits(t *testing.T) {
	if got := validateRules(packages); len(got) != 0 {
		t.Fatal(got)
	}
	for _, edge := range [][2]string{
		{"connector/worker", "ui"},
		{"connector/tcp", "cmd/perimeter/format"},
		{"connector/web", "connector/email"},
		{"core", "connector/worker"},
		{"core", "core/unlisted"},
	} {
		t.Run(strings.Join(edge[:], "/"), func(t *testing.T) {
			rules := maps.Clone(packages)
			r := rules[edge[0]]
			r.Deps = append(slices.Clone(r.Deps), edge[1])
			rules[edge[0]] = r
			if len(validateRules(rules)) == 0 {
				t.Fatal("explicit edge bypassed a hard boundary")
			}
		})
	}
	cycle := map[string]rule{"core/a": {library, []string{"core/b"}}, "core/b": {library, []string{"core/a"}}}
	if !hasViolation(validateRules(cycle), "cycle") {
		t.Fatal("cycle was accepted")
	}
	// Each direct edge is permitted; together they would make protocols depend
	// on each other through a shared helper, including on inactive platforms.
	rules := maps.Clone(packages)
	rules["connector/web"] = rule{protocol, []string{"connector/slots"}}
	rules["connector/slots"] = rule{library, []string{"connector/email"}}
	if !hasViolation(validateRules(rules), "another protocol") {
		t.Fatal("helper concealed a peer protocol")
	}
	rules = maps.Clone(packages)
	rules["core"] = rule{library, []string{"core/identity"}}
	if !hasViolation(validateRules(rules), "cmd/other: forbidden transitive") {
		t.Fatal("permitted closure widened Cedar's independent boundary")
	}
}

func TestTransitiveDependenciesCannotHideProductCoupling(t *testing.T) {
	for _, dependency := range []string{"gocloud.dev/blob", "github.com/open-policy-agent/opa/v1/rego", module + "/ui"} {
		p := compiledPackage{ImportPath: module + "/core/facts", Imports: []string{"example.test/helper"}, Deps: []string{"example.test/helper", dependency}}
		if reason := checkImport("core/facts", p.Imports[0], packages); reason != "" {
			t.Fatal("fixture's direct dependency must be allowed:", reason)
		}
		if !hasViolation(compiledViolations(p, packages), "transitive") {
			t.Fatalf("hidden dependency %s was accepted", dependency)
		}
	}
	p := compiledPackage{ImportPath: module + "/cmd/other", Imports: []string{module + "/core"}, Deps: []string{module + "/core", module + "/core/identity"}}
	if !hasViolation(compiledViolations(p, packages), "cmd/other: forbidden transitive") {
		t.Fatal("Cedar's independent dependency boundary was widened")
	}
	p = compiledPackage{ImportPath: module + "/core/facts", Incomplete: true}
	if !hasViolation(compiledViolations(p, packages), "incomplete") {
		t.Fatal("incomplete dependency information was accepted")
	}
}

func writeFixture(t *testing.T, root, name, text string) {
	t.Helper()
	filename := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(filename), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filename, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestCompiledChecksAllModulesOutsideWorkspace(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "go.mod", "module "+module+"\n\ngo 1.23\n")
	writeFixture(t, root, "core/facts/facts.go", "package facts\nconst Name = \"fixture\"\n")
	for _, dir := range modules[1:] {
		writeFixture(t, root, dir+"/go.mod", "module "+module+"/"+dir+"\n\ngo 1.23\nrequire "+module+" v0.0.0\nreplace "+module+" => ../..\n")
		code := "package " + packages[dir].packageName(dir) + "\n"
		if packages[dir].composes() {
			code += "func main() {}\n"
		}
		if dir == "cmd/other" || dir == "cmd/perimeter" {
			code = "package main\nimport _ \"" + module + "/core/facts\"\nfunc main() {}\n"
		}
		writeFixture(t, root, dir+"/main.go", code)
	}
	// A developer's workspace must not mask a missing or different module dependency.
	t.Setenv("GOWORK", filepath.Join(root, "does-not-exist.work"))
	got, violations := checkCompiled(root, modules, packages)
	if len(violations) != 0 || len(got) != len(modules) {
		t.Fatalf("compiled modules: %v; violations: %v", got, violations)
	}
	// A new module must not disappear from the root module's ./... scan.
	writeFixture(t, root, "core/hidden/go.mod", "module example.test/hidden\n\ngo 1.23\n")
	files, err := readSources(root, false, "")
	if err != nil {
		t.Fatal(err)
	}
	found := inspect(files, nil).Modules
	_, violations = checkCompiled(root, found, packages)
	if !hasViolation(violations, "unlisted Go module core/hidden") {
		t.Fatal(violations)
	}
	// A renamed nested module must not masquerade as an external dependency.
	writeFixture(t, root, "cmd/other/go.mod", "module example.test/disguised\n\ngo 1.23\nrequire "+module+" v0.0.0\nreplace "+module+" => ../..\n")
	_, violations = checkCompiled(root, modules, packages)
	if !hasViolation(violations, "unexpected import path example.test/disguised") {
		t.Fatal(violations)
	}
}

func TestGrowthIsMeasuredByPackageAndSeparatesTestsAndGeneration(t *testing.T) {
	beforeFiles := source("core/facts/facts.go", "package facts\nimport \"fmt\"\ntype Value[T any] struct { Public int; private int }\nfunc (*Value[T]) Exported() {}\nvar current int\n")
	afterFiles := source("core/facts/value.go", "package facts\nimport \"fmt\"\ntype Value[T any] struct { Public int; private int }\nfunc (*Value[T]) Exported() {}\n")
	afterFiles["core/facts/state.go"] = []byte("package facts\nvar current int\n")
	before, after := inspect(beforeFiles, nil), inspect(afterFiles, nil)
	change := compare(before, after)
	if len(change.Added)+len(change.Removed)+len(change.Exports.Added)+len(change.Exports.Removed)+len(change.Edges.Added)+len(change.Edges.Removed)+len(change.Globals.Added)+len(change.Globals.Removed) != 0 {
		t.Fatalf("splitting files changed the package graph or API: %+v", change)
	}
	if !slices.Equal(before.Packages["core/facts"].Exports, []string{"Value", "Value.Exported", "Value.Public"}) {
		t.Fatal(before.Packages["core/facts"].Exports)
	}
	afterFiles["core/facts/value_test.go"] = []byte("package facts_test\nfunc TestSomething() {}\n")
	afterFiles["core/facts/generated.go"] = []byte("// Code generated by fixture. DO NOT EDIT.\npackage facts\nvar generated int\n")
	afterFiles["core/facts/new.go"] = []byte("package facts\nimport \"net/http\"\nvar registry int\nfunc NewAPI() {}\n")
	newer := inspect(afterFiles, nil)
	change = compare(after, newer)
	if change.Lines["tests"] != 2 || change.Lines["generated_go"] != 3 || change.Lines["production_runtime_go"] != 4 {
		t.Fatal(change.Lines)
	}
	if !slices.Contains(change.Exports.Added, "core/facts -> NewAPI") || !slices.Contains(change.Edges.Added, "core/facts -> net/http") || !slices.Contains(change.Globals.Added, "core/facts -> registry") {
		t.Fatalf("growth was hidden: %+v", change)
	}
	if slices.Contains(newer.Packages["core/facts"].Exports, "TestSomething") {
		t.Fatal("test API counted as production")
	}
}

func TestBaseUsesExplicitCommitWithoutRunningOldChecker(t *testing.T) {
	root := t.TempDir()
	if _, err := git(root, "init", "-q"); err != nil {
		t.Fatal(err)
	}
	writeFixture(t, root, "core/facts/facts.go", "package facts\nconst Old = 1\n")
	for _, args := range [][]string{{"add", "."}, {"-c", "user.name=Fixture", "-c", "user.email=fixture@example.test", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture"}} {
		if _, err := git(root, args...); err != nil {
			t.Fatal(err)
		}
	}
	writeFixture(t, root, "core/facts/facts.go", "package facts\nconst New = 1\n")
	before, err := readSources(root, false, "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	after, err := readSources(root, true, "")
	if err != nil {
		t.Fatal(err)
	}
	change := compare(inspect(before, nil), inspect(after, nil))
	if !slices.Equal(change.Exports.Added, []string{"core/facts -> New"}) || !slices.Equal(change.Exports.Removed, []string{"core/facts -> Old"}) {
		t.Fatalf("base did not preserve committed source: %+v", change)
	}
}
