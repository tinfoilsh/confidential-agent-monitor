// Render the exact @tinfoilsh/tinfoil-icons components installed in ui/.
// Usage: node dev/sync-dashboard-icons.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(resolve(root, 'ui/package.json'));
const { version } = require('@tinfoilsh/tinfoil-icons/package.json');
const { createElement } = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const tinfoil = require('@tinfoilsh/tinfoil-icons');

const components = {
  activity: 'TfActivity',
  agents: 'TfBox',
  devices: 'TfComputer',
  sandboxes: 'TfBox',
  accounts: 'TfLink',
  presets: 'TfTools',
  rules: 'TfShieldCheck',
  policy: 'TfDocumentWithCode',
  integrations: 'TfTerminal',
  settings: 'TfWrench',
  search: 'TfMagnifyingGlass',
  refresh: 'TfRefresh',
  plus: 'TfPlus',
  help: 'TfQuestionMarkCircle',
  close: 'TfBoxX',
  copy: 'TfCopy',
  download: 'TfDownload',
  clock: 'TfClock',
  arrow: 'TfChevronRight',
  external: 'TfExternalLink',
  popout: 'TfApplicationWindow',
  dock: 'TfSidebarClose',
  sun: 'TfSunLightMode',
  moon: 'TfMoon',
  eye: 'TfEye',
  play: 'TfPlay',
  stop: 'TfStop',
  netlock: 'TfGlobeX',
};
const icons = Object.fromEntries(Object.entries(components).map(([name, component]) => [
  name, renderToStaticMarkup(createElement(tinfoil[component], { className: 'ui-icon', 'aria-hidden': true })),
]));
const files = {
  'ui/src/dashboard-icons.js': `// Generated by dev/sync-dashboard-icons.mjs. Do not edit SVGs by hand.
// @tinfoilsh/tinfoil-icons ${version}.
export const icons = ${JSON.stringify(icons, null, 2)};
`,
};
for (const [file, content] of Object.entries(files)) {
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${file} differs from @tinfoilsh/tinfoil-icons; rerun without --check`);
  } else {
    writeFileSync(path, content);
  }
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Copied'} ${Object.keys(icons).length} tinfoil-icons ${version} icons verbatim.`);
