// Render the exact Lucide components installed by websites-monorepo.
// Usage: node dev/sync-dashboard-icons.mjs [websites-monorepo path] [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = resolve(root, process.argv.slice(2).find(arg => arg !== '--check') ?? '../websites-monorepo');
const require = createRequire(resolve(source, 'apps/dashboard/package.json'));
const lucideRoot = resolve(source, 'apps/dashboard/node_modules/lucide-react');
const { version } = JSON.parse(readFileSync(resolve(lucideRoot, 'package.json'), 'utf8'));
if (version !== '0.473.0') throw new Error(`Expected websites-monorepo's Lucide 0.473.0, found ${version}`);
const { createElement } = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const lucide = await import(pathToFileURL(resolve(lucideRoot, 'dist/esm/lucide-react.js')));

const components = {
  activity: 'Activity',
  agents: 'Bot',
  devices: 'Laptop',
  sandboxes: 'Box',
  accounts: 'Plug',
  presets: 'LayoutGrid',
  rules: 'ShieldCheck',
  policy: 'FileCode2',
  integrations: 'Terminal',
  settings: 'Wrench',
  search: 'Search',
  refresh: 'RefreshCw',
  plus: 'Plus',
  help: 'CircleHelp',
  close: 'X',
  clock: 'Clock3',
  arrow: 'ChevronRight',
  external: 'ExternalLink',
  sun: 'Sun',
  moon: 'Moon',
};
const icons = Object.fromEntries(Object.entries(components).map(([name, component]) => [
  name, renderToStaticMarkup(createElement(lucide[component], { className: 'ui-icon', 'aria-hidden': true })),
]));
const files = {
  'ui/src/dashboard-icons.js': `// Generated by dev/sync-dashboard-icons.mjs. Do not edit SVGs by hand.
// websites-monorepo: lucide-react ${version}. License: icons/LUCIDE-LICENSE.
export const icons = ${JSON.stringify(icons, null, 2)};
`,
  'ui/public/icons/LUCIDE-LICENSE': readFileSync(resolve(lucideRoot, 'LICENSE'), 'utf8'),
};
for (const [file, content] of Object.entries(files)) {
  const path = resolve(root, file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${file} differs from websites-monorepo; rerun without --check`);
  } else {
    writeFileSync(path, content);
  }
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Copied'} ${Object.keys(icons).length} Lucide ${version} icons verbatim.`);
